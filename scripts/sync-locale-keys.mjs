function set(obj, keyPath, value) {
  const parts = keyPath.split('.')
  let cur = obj
  for (let i = 0; i < parts.length - 1; i++) {
    const p = parts[i]
    if (cur[p] == null || typeof cur[p] !== 'object') cur[p] = {}
    cur = cur[p]
  }
  if (cur[parts.at(-1)] === undefined) {
    cur[parts.at(-1)] = value
    return true
  }
  return false
}

